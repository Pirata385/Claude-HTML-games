#!/usr/bin/env node
// Água-Tinta — audio render tool (Node). Records every sound of the game into aquario-ascii/audio/*.mp3 and writes
// js/data/audio-manifest.js. The synth (synth-*.js, the game's former live audio engine) runs in headless Chromium
// on an OfflineAudioContext (render.html + render-page.js); ffmpeg (libmp3lame) encodes; each MP3 is then decoded
// back in Chromium to measure its decoder offset, true duration and loop seam, which go into the manifest.
//
//   node aquario-ascii/tools/audio-render/render.js            # render everything
//   node aquario-ascii/tools/audio-render/render.js theme-baia  # only ids containing a filter (manifest is merged)
//
// Needs: Playwright with Chromium (require('playwright')) and ffmpeg on PATH.
'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const vm = require('vm');
const { execFileSync } = require('child_process');
const { chromium } = require('playwright');

const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'audio');
const MANIFEST = path.join(ROOT, 'js', 'data', 'audio-manifest.js');
const TMP = fs.mkdtempSync(path.join(os.tmpdir(), 'aq-audio-'));
const ALIAS = { 'splash-jump': 'splashBig', reelClick: 'reel' };
// encoder settings (libmp3lame). Music, night takes and fight stems: VBR -q 7 (≈70–85 kbps stereo; measured closer
// to the source than CBR 96k, ≈12 % smaller). SFX and jingles: VBR -q 5. Reel loop 128k (clicks need it).
// Ambience (filtered noise, mono): CBR 64k — VBR spends too much on noise.
function encoderArgs(spec) {
  if (spec.kind === 'music' || spec.kind === 'stem') return ['-q:a', '7'];
  if (spec.kind === 'sfx' || spec.kind === 'jingle') return ['-q:a', '5'];
  if (spec.kind === 'loop') return ['-b:a', '128k'];
  if (spec.kind === 'ambience') return ['-b:a', '64k'];
  return ['-b:a', '32k'];
}
const r4 = (x) => Math.round(x * 10000) / 10000;
const r6 = (x) => Math.round(x * 1e6) / 1e6;   // loop points: sub-sample precision (1 µs ≈ 0.04 frame)

function loadManifest() {
  if (!fs.existsSync(MANIFEST)) return {};
  const sb = { AQ: {} };
  sb.window = sb;
  try { vm.runInNewContext(fs.readFileSync(MANIFEST, 'utf8'), sb); } catch (e) { return {}; }
  return JSON.parse(JSON.stringify(sb.AQ.AUDIO_MANIFEST || {}));
}

function writeManifest(m) {
  const order = ['sfx', 'jingle', 'loop', 'music', 'stem', 'ambience', 'silence'];
  const ids = Object.keys(m).sort((a, b) => (order.indexOf(m[a].kind) - order.indexOf(m[b].kind)) || (a < b ? -1 : a > b ? 1 : 0));
  const lines = ids.map((id) => '    ' + JSON.stringify(id) + ': ' + JSON.stringify(m[id]).replace(/"([a-zA-Z_]+)":/g, '$1: ').replace(/,(?=[a-zA-Z_]+: )/g, ', '));
  const src = `// Água-Tinta — audio manifest. GENERATED by tools/audio-render/render.js — do not edit by hand. Pure data.
// id → {file, kind, gain, duration, ...}. kind: sfx | jingle (dips the music for \`duck\` s) | loop (reel) |
// music (theme, loops between loopStart and loopEnd s, bpm, bars) | stem (fight layer, syncs with \`sync\`) |
// ambience (loop) | silence (iOS unlock). gain restores the level each file had before normalisation.
(function (AQ) {
  'use strict';

  AQ.AUDIO_MANIFEST = {
${lines.join(',\n')}
  };
})(window.AQ);
`;
  fs.writeFileSync(MANIFEST, src);
}

(async () => {
  const filters = process.argv.slice(2);
  const browser = await chromium.launch();
  const page = await browser.newPage();
  page.on('console', (m) => { if (m.type() === 'error') console.error('[page]', m.text()); });
  page.on('pageerror', (e) => console.error('[page error]', e.message));
  await page.goto('file://' + path.join(__dirname, 'render.html'));
  const all = await page.evaluate(() => window.AQR.list());
  const todo = all.filter((s) => !filters.length || filters.some((f) => s.id.includes(f)));
  const manifest = filters.length ? loadManifest() : {};
  const rows = [];
  let worstSeam = 0;
  for (const spec of todo) {
    const t0 = Date.now();
    const r = await page.evaluate((id) => window.AQR.render(id), spec.id);
    const wav = path.join(TMP, spec.id + '.wav');
    const mp3 = path.join(OUT, spec.file);
    fs.mkdirSync(path.dirname(mp3), { recursive: true });
    fs.writeFileSync(wav, Buffer.from(r.wav, 'base64'));
    execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', wav, '-c:a', 'libmp3lame', ...encoderArgs(spec), '-ar', '44100', mp3]);
    fs.unlinkSync(wav);
    const an = await page.evaluate(([id, b64]) => window.AQR.analyse(id, b64), [spec.id, fs.readFileSync(mp3).toString('base64')]);
    const e = { file: 'audio/' + spec.file, kind: spec.kind, gain: r4(r.gain), duration: r4(an.duration), channels: r.channels };
    if (r.loop) {
      e.loopStart = r6(an.loopStart);
      e.loopEnd = r6(an.loopEnd);
      if (an.seam > worstSeam) worstSeam = an.seam;
    }
    if (r.meta.bpm) { e.bpm = r.meta.bpm; e.bars = r.meta.bars; }
    if (r.meta.clicksPerSec) e.clicksPerSec = r.meta.clicksPerSec;
    if (spec.theme && spec.kind !== 'music') e.zone = spec.theme;
    if (spec.night) e.night = true;
    if (spec.sync) e.sync = spec.sync;
    if (spec.duck) e.duck = spec.duck;
    manifest[spec.id] = e;
    for (const a of Object.keys(ALIAS)) if (ALIAS[a] === spec.id) manifest[a] = Object.assign({}, e, { alias: spec.id });
    const kb = fs.statSync(mp3).size / 1024;
    rows.push([spec.id, spec.kind, kb.toFixed(1) + ' KB', an.duration.toFixed(2) + ' s', 'gain ' + r.gain.toFixed(3), 'off ' + an.offset,
      'peak ' + an.decodedPeak.toFixed(3), r.loop ? 'seam x' + an.seam.toFixed(2) + ' rel ' + an.seamRel.toFixed(3) + ' (ref ' + r.refSeam.toExponential(1) + ')' : '', ((Date.now() - t0) / 1000).toFixed(1) + ' s']);
    console.log(rows[rows.length - 1].join('  '));
  }
  writeManifest(manifest);
  await browser.close();
  fs.rmSync(TMP, { recursive: true, force: true });
  let total = 0, n = 0;
  (function walk(d) { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else if (/\.mp3$/.test(f)) { total += fs.statSync(p).size; n++; } } })(OUT);
  console.log(`\n${todo.length} rendered; audio/ holds ${n} files, ${(total / 1048576).toFixed(2)} MB; worst decoded loop seam ${worstSeam.toFixed(4)}`);
})().catch((e) => { console.error(e); process.exit(1); });
